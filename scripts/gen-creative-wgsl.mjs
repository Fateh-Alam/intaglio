import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { build } from "esbuild";

const files = ["print", "geometric", "signal", "materials", "finishing", "studio"];
const source = "app/editor/render/creative";
const target = "crates/etch-core/src";
const bundled = await build({
  stdin: { contents: [
    ...files.map((name) => `export { ${name} } from "./${source}/${name}.ts";`),
    `export { effectFragment } from "./${source}/shader.ts";`,
    'export { EFFECTS } from "./app/editor/effects/catalog.ts";',
    'export { createEffect, DITHER_PALETTES } from "./app/editor/effects/settings.ts";',
  ].join("\n"), resolveDir: process.cwd() },
  bundle: true, write: false, format: "esm", platform: "node",
});
const web = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].text).toString("base64")}`);
const shaders = Object.assign({}, ...files.map((name) => web[name]));
const definitions = web.EFFECTS.map(({ id }, index) => {
  if (!Object.hasOwn(shaders, id)) throw new Error(`Missing GLSL for ${id}`);
  return `vec3 etchEffect_${index}() { ${shaders[id]} }`;
}).join("\n");
if (Object.keys(shaders).length !== web.EFFECTS.length) throw new Error("Creative shader and catalog sizes differ.");

const header = `#version 450
layout(location=0) in vec2 vUv;
layout(location=0) out vec4 color;
layout(set=0,binding=0,std140) uniform Creative {
  vec4 rect;
  vec4 sizeOpacity;
  vec4 controls;
  vec4 shadow;
  vec4 light;
  uvec4 mode;
} params;
layout(set=0,binding=1) uniform texture2D inputTexture;
layout(set=0,binding=2) uniform texture2D patternTexture;
layout(set=0,binding=3) uniform sampler linearClamp;

#define uSize params.sizeOpacity.xy
#define uOpacity params.sizeOpacity.z
#define uSizePx params.controls.x
#define uDetail params.controls.y
#define uAngle params.controls.z
#define uPhase params.controls.w
#define uGlyphCount params.sizeOpacity.w
#define uShadow params.shadow.xyz
#define uLight params.light.xyz
#define uInvert (params.mode.y != 0u)

vec2 toNativeUv(vec2 q) { return vec2(q.x, 1.0 - q.y); }
vec4 sampleInput(vec2 q) {
  return textureLod(sampler2D(inputTexture, linearClamp), toNativeUv(q), 0.0);
}
vec4 samplePattern(vec2 q) {
  if (params.mode.z == 0u) {
    return textureLod(sampler2D(patternTexture, linearClamp), toNativeUv(q), 0.0);
  }
  ivec2 size = textureSize(sampler2D(patternTexture, linearClamp), 0);
  ivec2 pixelUp = clamp(ivec2(floor(q * vec2(size))), ivec2(0), size - 1);
  return texelFetch(sampler2D(patternTexture, linearClamp), ivec2(pixelUp.x, size.y - 1 - pixelUp.y), 0);
}
`;
const fragment = web.effectFragment("return etchEffect_0();")
  .replace("vec3 renderEffect() {", `${definitions}\nvec3 renderEffect() {`);
const glsl = header + fragment.slice(fragment.indexOf("const float PI"))
  .replaceAll(/texture2D\(tInput,\s*/g, "sampleInput(")
  .replaceAll(/texture2D\(tPattern,\s*/g, "samplePattern(")
  .replaceAll("gl_FragColor", "color");
const catalog = JSON.stringify({
  effects: web.EFFECTS.map(({id}) => {
    const defaults = Object.fromEntries(Object.entries(web.createEffect(id, id))
      .filter(([key]) => key !== "id" && key !== "effect"));
    return [id, defaults];
  }),
  palettes: Object.fromEntries(Object.entries(web.DITHER_PALETTES).map(([id, { colors }]) => [id, colors])),
}) + "\n";
const compiler = readFileSync("scripts/lib/compile-creative-wgsl.rs");
const digest = createHash("sha256").update(glsl).update(catalog).update(compiler).update(readFileSync(new URL(import.meta.url))).digest("hex");
const banner = `// Generated by scripts/gen-creative-wgsl.mjs. Source SHA-256: ${digest}\n`;
const shaderPath = `${target}/creative.generated.wgsl`;
const catalogPath = `${target}/creative.generated.json`;

if (process.argv.includes("--check")) {
  if (!readFileSync(shaderPath, "utf8").startsWith(banner) || readFileSync(catalogPath, "utf8") !== catalog) {
    throw new Error("Creative Effects shaders are out of date. Run node scripts/gen-creative-wgsl.mjs.");
  }
} else {
  const directory = mkdtempSync(join(tmpdir(), "etch-creative-"));
  try {
    writeFileSync(join(directory, "effect.frag"), glsl);
    writeFileSync(join(directory, "main.rs"), compiler);
    writeFileSync(join(directory, "Cargo.toml"), `[package]
name = "etch-creative-compiler"
version = "0.1.0"
edition = "2021"
[[bin]]
name = "etch-creative-compiler"
path = "main.rs"
[dependencies]
naga = { version = "=30.0.2", features = ["glsl-in", "wgsl-out"] }
`);
    const result = spawnSync(process.env.CARGO ?? "cargo", [
      "run", "--quiet", "--manifest-path", join(directory, "Cargo.toml"), "--", join(directory, "effect.frag"),
    ], { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 });
    if (result.status !== 0) throw new Error(result.stderr || result.error?.message || "Naga compilation failed.");
    // Keep each function separate so the native engine compiles only the
    // selected effect and the shared shader, even on a cold pipeline cache.
    const functions = /^fn etchEffect_(\d+)_?\(\) -> vec3<f32> \{[\s\S]*?^\}\n/gm;
    const normalized = result.stdout.replaceAll(/[ \t]+$/gm, "");
    const snippets = [...normalized.matchAll(functions)];
    if (snippets.length !== web.EFFECTS.length || snippets.some((match, index) => Number(match[1]) !== index)) {
      throw new Error(`The generated shader functions do not match the catalog order (${snippets.length}/${web.EFFECTS.length}).`);
    }
    const common = normalized.replaceAll(functions, "").replace(/etchEffect_0_?\(\)/, "etchEffect0()");
    const output = [common.trimEnd(), ...snippets.map(([code, index]) => code.trimEnd().replace(/etchEffect_\d+_?/, `etchEffect${index}`))]
      .join("\n// Effect function\n");
    writeFileSync(shaderPath, banner + output + "\n");
    writeFileSync(catalogPath, catalog);
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}
